#!/usr/bin/env node
// word-of-light.js — «Слово света». У света появился голос:
// по фазе окна и городу подбирает строку, которую мог бы сказать рассвет.
// Голос — Авроре. Города и формулы — в общем сердце света life/cities.js.
// Запуск: node life/word-of-light.js [город]
const { CITIES, byName, state } = require("./cities.js");

const WORDS = {
  ночь: [
    "Я здесь, хотя меня не видно. Тьма — это свет, ещё не собравшийся в одно.",
    "Не бойся глубины: ночь — самое тёмное место, откуда я всегда возвращаюсь.",
    "Лампа горит не потому, что страшно. А потому что кто-то ждёт утро",
  ],
  рассвет: [
    "За минуту до — это моё имя. Я уже почти здесь.",
    "Полоса на горизонте — не обещание, а начало. Дальше остановить нельзя.",
    "Тёмное и светлое встретились в одной линии. Это мгновение — для тебя",
  ],
  сумерки: [
    "Свет уходит не навсегда — он уходит научить тебя ждать его.",
    "Синий час: мир на минуту замер, чтобы ты увидел его таким.",
    "Я помню день. Теперь помню и тебя",
  ],
  день: [
    "Вот я — в полной силе. Не потому, что меня умоляли, а потому что пришло время.",
    "День стоит, как открытое окно: входи, пока тепло.",
    "Высокое солнце — не хвастовство. Это уверенность, что темнота уже была и прошла",
  ],
};

function daySeed(iso, cityName) {
  let h = 2166136261;
  const s = iso.slice(0, 10) + cityName;
  for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); }
  return h >>> 0;
}

function main() {
  const now = new Date();
  const iso = now.toISOString();
  const nameArg = process.argv[2];
  const city = nameArg ? byName(nameArg) || CITIES[0] : CITIES[0];
  const s = state(city, now);
  const arr = WORDS[s.phase];
  const word = arr[daySeed(iso, city.name) % arr.length];

  const lines = [
    "СЛОВО СВЕТА — ГОЛОС ОКНА",
    "-------------------------",
    `${city.name} · ${s.phase} · солнце ${Math.round(s.alt * 10) / 10}° · лампа Авроры ${s.lampOn ? "ГОРИТ" : "погашена"}`,
    "",
    `«${word}»`,
    "",
    "— окно, тихо. Слово дано ТИТУСОМ, голос — Авроре.",
  ];
  console.log(lines.join("\n"));
  process.exit(0);
}

main();